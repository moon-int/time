export function t(lang, key) {
  return (I18N[lang] && I18N[lang][key]) || I18N.de[key] || key;
}

export function tf(lang, key, vars) {
  return t(lang, key).replace(/\{(\w+)\}/g, (_, name) => (name in vars ? vars[name] : ""));
}

export function applyI18n(lang) {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(lang, el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(lang, el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(lang, el.dataset.i18nTitle);
    el.setAttribute("aria-label", t(lang, el.dataset.i18nTitle));
  });
}
